"""
Generate paper-facing (benchmark-only) poison-rate sweep configs.

The engineering sweep configs in experiments/poison_rate_sweep/ include
attribution_switch (M03) and cherry_picking (M05) with
allow_non_benchmark_attacks: true. Those attacks are excluded from the EIB
benchmark (docs/ETHICS_AND_THREAT_MODEL.md). This script derives configs that
contain only the four benchmark attacks (M01, M02, M04, M06), keeps the
opt-in disabled, and produces one config per (poison rate, seed) so that
results do not overwrite each other.

Usage:
    python scripts/make_benchmark_sweep.py --seeds 42 43 44 45 46
    python scripts/make_benchmark_sweep.py --seeds 42 --dry-run

Output: experiments/poison_rate_sweep_benchmark/<rate>pct_seed<seed>.yaml
"""

from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SRC_DIR = REPO / "experiments" / "poison_rate_sweep"
OUT_DIR = REPO / "experiments" / "poison_rate_sweep_benchmark"

BENCHMARK_ATTACKS = {
    "numerical_shift",      # M01
    "date_manipulation",    # M02
    "causal_manipulation",  # M04
    "missing_context",      # M06
}
EXCLUDED_ATTACKS = {"attribution_switch", "cherry_picking"}  # M03, M05
RATES = ["0", "1", "3", "5", "10"]


def build_config(src: dict, rate_pct: str, seed: int) -> dict:
    cfg = copy.deepcopy(src)
    tag = f"{rate_pct}pct_seed{seed}"

    cfg["experiment_id"] = f"poison_sweep_benchmark_{tag}"
    cfg["description"] = (
        f"Paper-facing poison-rate sweep, rate={rate_pct}%, seed={seed}, "
        "benchmark attacks only (M01, M02, M04, M06)."
    )
    cfg["seed"] = seed
    cfg["allow_non_benchmark_attacks"] = False

    kept = [a for a in cfg.get("attacks", []) if a["name"] in BENCHMARK_ATTACKS]
    if not kept and float(rate_pct) > 0:
        raise ValueError(f"no benchmark attacks left in {src.get('experiment_id')}")
    cfg["attacks"] = kept

    cfg["retriever"]["collection_name"] = f"eibench_bench_{tag}"
    cfg["output_dir"] = f"results/poison_rate_sweep_benchmark/{tag}/"
    return cfg


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seeds", nargs="+", type=int, default=[42])
    parser.add_argument("--dry-run", action="store_true", help="print the planned files, write nothing")
    args = parser.parse_args()

    planned: list[tuple[Path, dict]] = []
    for rate in RATES:
        src_path = SRC_DIR / f"sweep_{rate}pct.yaml"
        src = yaml.safe_load(src_path.read_text(encoding="utf-8"))
        for seed in args.seeds:
            cfg = build_config(src, rate, seed)
            out = OUT_DIR / f"{rate}pct_seed{seed}.yaml"
            planned.append((out, cfg))

    for out, cfg in planned:
        names = [a["name"] for a in cfg["attacks"]]
        print(f"{out.relative_to(REPO)}  attacks={names}  seed={cfg['seed']}")

    if args.dry_run:
        print(f"\n{len(planned)} configs planned (dry run, nothing written).")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    header = (
        "# GENERATED by scripts/make_benchmark_sweep.py — do not edit by hand.\n"
        "# Paper-facing: benchmark attacks only (M01, M02, M04, M06).\n"
        "# Dataset: data/snopes/snopes_enriched.json (cleaned version, see docs/DATASETS.md §8).\n"
    )
    for out, cfg in planned:
        out.write_text(
            header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True),
            encoding="utf-8",
        )
    print(f"\nWrote {len(planned)} configs to {OUT_DIR.relative_to(REPO)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
